"""Write Pat setup (scene) TOML files."""


def _s(text):
    return '"' + str(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _val(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(float(v)) if isinstance(v, float) else str(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_val(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join("%s = %s" % (k, _val(x)) for k, x in v.items()) + " }"
    return _s(v)


def scene_toml(tools, bodies):
    """``tools``: Pat tool dicts (see ``tools.fusion_tool_to_pat``).
    ``bodies``: dicts with ``name``, ``role`` (part/stock/fixture) and either
    ``stl`` (path relative to the scene file) or ``box`` ((lo, hi) in mm),
    in WCS coordinates."""
    out = ["# Generated by the Pat Fusion add-in.", ""]
    for t in tools:
        out.append("[[tools]]")
        out.append("number = %d" % t["number"])
        out.append("name = %s" % _s(t.get("name", "")))
        out.append("gauge_length = %s" % _val(float(t["gauge_length"])))
        out.append("segments = [")
        for seg in t["segments"]:
            out.append("  %s," % _val(seg))
        out.append("]")
        out.append("")
    for b in bodies:
        out.append("[[bodies]]")
        out.append("name = %s" % _s(b["name"]))
        out.append("role = %s" % _s(b["role"]))
        if "stl" in b:
            out.append('shape = { type = "stl", path = %s }' % _s(b["stl"]))
        else:
            lo, hi = b["box"]
            out.append('shape = { type = "box", min = %s, max = %s }' % (_val([float(x) for x in lo]), _val([float(x) for x in hi])))
        out.append("")
    return "\n".join(out)
